import { computeScore, scoreBandLabel } from "../scoring";
import { listAllFindings } from "../findings";
import { getPrioritizedChecklist } from "../checklist";

export function buildMarkdownReport(owner: string): string {
  const all = listAllFindings(owner);
  const open = all.filter((f) => f.status === "open");
  const { score } = computeScore(open);
  const checklist = getPrioritizedChecklist(owner);
  const generatedAt = new Date().toISOString();

  const lines: string[] = [];
  lines.push(`# Digital Footprint Report`);
  lines.push("");
  lines.push(`Generated: ${generatedAt}`);
  lines.push("");
  lines.push(`## Exposure score: ${score} / 100 — ${scoreBandLabel(score)}`);
  lines.push("");
  lines.push(`Open findings: ${open.length} (critical: ${open.filter((f) => f.severity === "critical").length}, high: ${open.filter((f) => f.severity === "high").length}, medium: ${open.filter((f) => f.severity === "medium").length}, low: ${open.filter((f) => f.severity === "low").length})`);
  lines.push("");
  lines.push(`## Prioritized cleanup checklist`);
  lines.push("");
  if (checklist.length === 0) {
    lines.push("Nothing open — nice work.");
  }
  for (const item of checklist) {
    lines.push(`- [ ] **[${item.severity.toUpperCase()}]** ${item.title}`);
    lines.push(`  - ${item.description}`);
    lines.push(`  - Recommendation: ${item.recommendation}`);
    if (item.links.length) {
      lines.push(`  - Links: ${item.links.map((l) => `[${l.label}](${l.url})`).join(", ")}`);
    }
  }
  lines.push("");
  lines.push(`## All findings (including resolved)`);
  lines.push("");
  lines.push(`| Severity | Title | Module | Status | First seen | Last seen |`);
  lines.push(`|---|---|---|---|---|---|`);
  for (const f of all) {
    lines.push(`| ${f.severity} | ${f.title.replace(/\|/g, "\\|")} | ${f.module} | ${f.status} | ${f.first_seen_at} | ${f.last_seen_at} |`);
  }
  lines.push("");
  lines.push("---");
  lines.push("_This report is for the account owner's own private use. Generated by Digital Footprint Checker, which must never be used to investigate anyone else._");
  return lines.join("\n");
}
