import PDFDocument from "pdfkit";
import { computeScore, scoreBandLabel } from "../scoring";
import { listAllFindings } from "../findings";
import { getPrioritizedChecklist } from "../checklist";

export function buildPdfReport(owner: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const all = listAllFindings(owner);
    const open = all.filter((f) => f.status === "open");
    const { score } = computeScore(open);
    const checklist = getPrioritizedChecklist(owner);

    doc.fontSize(20).text("Digital Footprint Report", { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(10).fillColor("gray").text(`Generated: ${new Date().toISOString()}`);
    doc.fillColor("black");
    doc.moveDown(1);

    doc.fontSize(16).text(`Exposure score: ${score} / 100 — ${scoreBandLabel(score)}`);
    doc.moveDown(0.5);
    doc
      .fontSize(11)
      .text(
        `Open findings: ${open.length}  (critical ${open.filter((f) => f.severity === "critical").length}, high ${open.filter((f) => f.severity === "high").length}, medium ${open.filter((f) => f.severity === "medium").length}, low ${open.filter((f) => f.severity === "low").length})`
      );
    doc.moveDown(1);

    doc.fontSize(16).text("Prioritized cleanup checklist");
    doc.moveDown(0.5);
    if (checklist.length === 0) {
      doc.fontSize(11).text("Nothing open — nice work.");
    }
    for (const item of checklist) {
      doc.fontSize(12).fillColor("black").text(`[${item.severity.toUpperCase()}] ${item.title}`, { continued: false });
      doc.fontSize(10).fillColor("#333333").text(item.description);
      doc.fontSize(10).fillColor("#000080").text(`Recommendation: ${item.recommendation}`);
      for (const link of item.links) {
        doc.fontSize(9).fillColor("blue").text(`${link.label}: ${link.url}`, { link: link.url, underline: true });
      }
      doc.fillColor("black");
      doc.moveDown(0.7);
      if (doc.y > 700) doc.addPage();
    }

    doc.addPage();
    doc.fontSize(16).text("All findings (including resolved)");
    doc.moveDown(0.5);
    for (const f of all) {
      doc.fontSize(10).text(`[${f.severity}] ${f.title} — ${f.module} — ${f.status} (first seen ${f.first_seen_at})`);
      if (doc.y > 740) doc.addPage();
    }

    doc.moveDown(1);
    doc.fontSize(8).fillColor("gray").text("This report is for the account owner's own private use. Generated by Digital Footprint Checker, which must never be used to investigate anyone else.");

    doc.end();
  });
}
